#!/usr/bin/env node
//
// t27-surface-census.mjs — the migration surface, counted.
//
// Issue gHashTag/trios#1338 ("The migration surface, counted: which files
// duplicate a rule that already has a .t27 source"). For every .t27 spec in
// the tree the census answers two questions: does a hand-written file exist
// that implements the same rule, and how many lines is it? The pairing rule
// is by BASENAME, because that is the convention this tree already follows
// (queen_core.t27 next to queen_core.rs) and a rule stated as a convention is
// checkable, while a rule stated as a judgement is not.
//
// What it counts, in one paragraph:
//   - specs: every .t27 file under rings/, walked naively (worktree copies
//     included) so the "found" number can be compared with the hand count,
//     then again with worktree copies excluded, which is the real census.
//   - twins: hand-written .rs/.zig/.c/.v/.swift/.ts files anywhere under the
//     trios tree, excluding node_modules, .worktrees, .claude/worktrees and
//     .git, and excluding machine-written output (a gen/ directory, or a
//     "generated by t27c" banner). Generated files are not hand-written code
//     and counting them would lie about the surface this epic must zero.
//
// Runtime: Node standard library only (node:fs, node:path, node:url). Every
// path it reads is derived from this script's own location; it never touches
// anything outside the trios tree, and in particular never reads anything
// under /Users/playra/t27 (FR-004).
//
// Output: a summary on stdout and a full per-spec table in
// trios/docs/t27-surface-census.md, next to this tool's own conventions.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { basename, dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const TRIOS_ROOT = dirname(dirname(SCRIPT_PATH)); // .../trios (contains tools/)
const RINGS_DIR = join(TRIOS_ROOT, 'rings');
const OUT_PATH = join(TRIOS_ROOT, 'docs', 't27-surface-census.md');

// Extensions that can hold a hand-written implementation of a rule.
const TWIN_EXTENSIONS = new Set(['.rs', '.zig', '.c', '.v', '.swift', '.ts']);

// Directories never descended into when looking for twins (FR-001). The
// .claude/worktrees entry is matched on the pair of path segments, because
// that is where agent worktree copies land in this tree.
const SKIP_DIRECTORY_NAMES = new Set(['node_modules', '.worktrees', '.git']);
const GEN_DIRECTORY_NAMES = new Set(['gen']); // t27c output convention

// Banners carried by files this tree's compiler generates. A file that
// declares itself generated is machine-written, not hand-written, whatever
// directory it lives in.
const GENERATED_BANNER = /generated by t27c|generated from \.?t27/i;

const PAIRING_RULE_TEXT = [
  'A .t27 spec pairs with any hand-written file whose basename (filename',
  'without extension) is identical to the spec basename, among extensions',
  '.rs .zig .c .v .swift .ts, anywhere under trios/ excluding node_modules,',
  '.worktrees, .claude/worktrees, .git and generated output (gen/ directories',
  'and "generated by t27c" banners). To check any row by hand: strip the',
  'extension from the spec filename and search the tree for that stem.',
].join(' ');

// ---------------------------------------------------------------------------
// Filesystem helpers
// ---------------------------------------------------------------------------

/** Depth-first walk. `skipDirectory(absPath, name)` returning true prunes. */
function walkFiles(root, skipDirectory, onFile) {
  const stack = [root];
  while (stack.length > 0) {
    const dir = stack.pop();
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!entry.isSymbolicLink() && !skipDirectory(full, entry.name)) {
          stack.push(full);
        }
      } else if (entry.isFile()) {
        onFile(full);
      }
    }
  }
}

/** True when a repo-relative path runs through a worktree copy. */
function isWorktreeCopy(relPath) {
  const segments = relPath.split(sep);
  for (let i = 0; i < segments.length; i += 1) {
    if (segments[i] === '.worktrees') return true;
    if (segments[i] === '.claude' && segments[i + 1] === 'worktrees') return true;
  }
  return false;
}

/** True when a repo-relative path runs through a generated-output directory. */
function isUnderGeneratedDir(relPath) {
  return relPath.split(sep).includes('gen');
}

/** Line count with wc -l semantics: newlines, plus one for an unterminated last line. */
function countLines(text) {
  if (text.length === 0) return 0;
  let lines = 0;
  for (let i = 0; i < text.length; i += 1) {
    if (text.charCodeAt(i) === 10) lines += 1;
  }
  if (text.charCodeAt(text.length - 1) !== 10) lines += 1;
  return lines;
}

function readLines(path) {
  return countLines(readFileSync(path, 'utf8'));
}

/** First lines of a file, for the generated-banner check. */
function readHead(path) {
  const text = readFileSync(path, 'utf8');
  return text.split('\n', 3).join('\n');
}

// ---------------------------------------------------------------------------
// The census
// ---------------------------------------------------------------------------

/** Collect every .t27 under rings/ — the naive count, worktree copies included. */
function findSpecFiles() {
  const found = [];
  walkFiles(RINGS_DIR, () => false, (path) => {
    if (path.endsWith('.t27')) found.push(path);
  });
  found.sort();
  return found;
}

/**
 * Collect hand-written twin candidates for the given spec basenames, and the
 * generated files that were refused as twins. Only files whose basename
 * matches a spec are ever opened; everything else is irrelevant to the census.
 */
function findTwinCandidates(specBasenames) {
  const handWritten = new Map(); // basename -> [{ path, lines }]
  const generated = []; // [{ path, reason }]
  walkFiles(
    TRIOS_ROOT,
    (path, name) => {
      if (SKIP_DIRECTORY_NAMES.has(name)) return true;
      if (name === 'worktrees' && basename(dirname(path)) === '.claude') return true;
      return false;
    },
    (path) => {
      const ext = extname(path);
      if (!TWIN_EXTENSIONS.has(ext)) return;
      const stem = basename(path, ext);
      if (!specBasenames.has(stem)) return; // cannot pair with anything
      const rel = relative(TRIOS_ROOT, path);
      if (isUnderGeneratedDir(rel)) {
        generated.push({ path: rel, reason: 'under gen/ (t27c output)' });
        return;
      }
      if (GENERATED_BANNER.test(readHead(path))) {
        generated.push({ path: rel, reason: 'carries a generation banner' });
        return;
      }
      const list = handWritten.get(stem) ?? [];
      list.push({ path: rel, lines: readLines(path) });
      handWritten.set(stem, list);
    },
  );
  for (const list of handWritten.values()) list.sort((a, b) => a.path.localeCompare(b.path));
  generated.sort((a, b) => a.path.localeCompare(b.path));
  return { handWritten, generated };
}

/**
 * Pair every spec with the hand-written twins that share its basename. This is
 * the whole pairing law of the census: basename equality, nothing else — no
 * path proximity, no content similarity. Stated so a reader can check any row.
 */
function pairByBasename(specs, twinsByBasename) {
  return specs.map((spec) => ({
    spec,
    twins: twinsByBasename.get(spec.basename) ?? [],
  }));
}

/** Production rings (rings/T27-*) are kept apart from mesh specs (FR-003). */
function classifySpec(relPath) {
  const p = relPath.split(sep).join('/');
  if (p.startsWith('rings/T27-')) return 'production';
  if (p.includes('RUST-13/trios-mesh')) return 'mesh';
  return 'other';
}

function main() {
  // -- specs --------------------------------------------------------------
  const allSpecPaths = findSpecFiles(); // naive: worktree copies included
  const distinctSpecs = allSpecPaths
    .filter((path) => !isWorktreeCopy(relative(TRIOS_ROOT, path)))
    .map((path) => {
      const rel = relative(TRIOS_ROOT, path);
      return { path: rel, basename: basename(rel, '.t27'), lines: readLines(path) };
    });
  const worktreeCopyCount = allSpecPaths.length - distinctSpecs.length;

  const specBasenames = new Set(distinctSpecs.map((s) => s.basename));
  const { handWritten, generated } = findTwinCandidates(specBasenames);

  // -- pairing ------------------------------------------------------------
  const pairs = pairByBasename(distinctSpecs, handWritten);
  const paired = pairs.filter((row) => row.twins.length > 0);
  const unpaired = pairs.filter((row) => row.twins.length === 0);

  // Hand-written lines with a spec twin: every hand-written file that pairs
  // with at least one spec, counted once. This is the number the one-rule-
  // one-source epic exists to drive to zero.
  const twinFilesSeen = new Set();
  let handWrittenLinesWithTwin = 0;
  for (const row of paired) {
    for (const twin of row.twins) {
      if (!twinFilesSeen.has(twin.path)) {
        twinFilesSeen.add(twin.path);
        handWrittenLinesWithTwin += twin.lines;
      }
    }
  }

  const bySection = { production: 0, mesh: 0, other: 0 };
  let specLinesTotal = 0;
  for (const spec of distinctSpecs) {
    bySection[classifySpec(spec.path)] += 1;
    specLinesTotal += spec.lines;
  }

  // -- stdout summary -------------------------------------------------------
  const lines = [];
  lines.push('t27 surface census');
  lines.push('==================');
  lines.push(`pairing rule: ${PAIRING_RULE_TEXT}`);
  lines.push('');
  lines.push(`.t27 files found: ${allSpecPaths.length}`);
  lines.push(`.t27 files after excluding worktree copies: ${distinctSpecs.length}`);
  lines.push(`  worktree copies excluded: ${worktreeCopyCount}`);
  lines.push(`  production rings (rings/T27-*): ${bySection.production}`);
  lines.push(`  mesh specs (rings/RUST-13/trios-mesh): ${bySection.mesh}`);
  if (bySection.other > 0) lines.push(`  other locations: ${bySection.other}`);
  lines.push('');
  lines.push(`distinct specs paired with hand-written code: ${paired.length}`);
  lines.push(`distinct specs unpaired: ${unpaired.length}`);
  lines.push(`hand-written lines with a spec twin: ${handWrittenLinesWithTwin}`);
  for (const row of paired) {
    for (const twin of row.twins) {
      lines.push(`  ${row.spec.basename}: ${row.spec.path} (${row.spec.lines}) <-> ${twin.path} (${twin.lines})`);
    }
  }
  lines.push(`generated twins refused (machine-written, not counted): ${generated.length}`);
  lines.push('');
  lines.push(`wrote ${relative(dirname(TRIOS_ROOT), OUT_PATH)}`);
  const stdout = lines.join('\n');
  console.log(stdout);

  // -- markdown report ------------------------------------------------------
  const date = new Date().toISOString().slice(0, 10);
  const md = [];
  md.push('# T27 surface census');
  md.push('');
  md.push(`Generated ${date} by \`node trios/tools/t27-surface-census.mjs\` (issue gHashTag/trios#1338).`);
  md.push('');
  md.push('## Pairing rule');
  md.push('');
  md.push(PAIRING_RULE_TEXT);
  md.push('');
  md.push('## Method');
  md.push('');
  md.push('- Specs are every `.t27` file under `rings/`, walked naively first (worktree copies included — that is the number a hand count produces), then with worktree copies excluded, which is the census proper.');
  md.push('- Twins are hand-written files with extension `.rs`, `.zig`, `.c`, `.v`, `.swift` or `.ts` anywhere under `trios/`, excluding `node_modules`, `.worktrees`, `.claude/worktrees` and `.git`.');
  md.push('- Generated output is not hand-written code and is refused as a twin: files under a `gen/` directory, and files carrying a `generated by t27c` banner. Refused files are listed below.');
  md.push('- Line counts are `wc -l` semantics: one per newline, plus one for an unterminated final line.');
  md.push('- The tool uses the Node standard library only and reads nothing outside this tree; every path is derived from the script location. Nothing under `/Users/playra/t27` is read.');
  md.push('');
  md.push('## Summary');
  md.push('');
  md.push('| measure | count |');
  md.push('| --- | ---: |');
  md.push(`| .t27 files found (naive, worktree copies included) | ${allSpecPaths.length} |`);
  md.push(`| .t27 files after excluding worktree copies | ${distinctSpecs.length} |`);
  md.push(`| — worktree copies excluded | ${worktreeCopyCount} |`);
  md.push(`| — production rings (\`rings/T27-*\`) | ${bySection.production} |`);
  md.push(`| — mesh specs (\`rings/RUST-13/trios-mesh\`) | ${bySection.mesh} |`);
  if (bySection.other > 0) md.push(`| — other locations | ${bySection.other} |`);
  md.push(`| distinct specs paired with hand-written code | ${paired.length} |`);
  md.push(`| distinct specs unpaired | ${unpaired.length} |`);
  md.push(`| spec lines across distinct specs | ${specLinesTotal} |`);
  md.push(`| **hand-written lines with a spec twin** | **${handWrittenLinesWithTwin}** |`);
  md.push('');
  md.push(`Hand-written lines with a spec twin: ${handWrittenLinesWithTwin} — the number the one-rule-one-source epic exists to drive to zero.`);
  md.push('');

  const sectionTitle = {
    production: 'Production rings (rings/T27-*)',
    mesh: 'Mesh specs (rings/RUST-13/trios-mesh)',
    other: 'Other locations',
  };
  for (const section of ['production', 'mesh', 'other']) {
    const rows = pairs.filter((row) => classifySpec(row.spec.path) === section);
    if (rows.length === 0) continue;
    md.push(`## ${sectionTitle[section]} — ${rows.length} distinct spec${rows.length === 1 ? '' : 's'}`);
    md.push('');
    md.push('| spec | spec lines | hand-written twin | twin lines |');
    md.push('| --- | ---: | --- | ---: |');
    for (const row of rows) {
      if (row.twins.length === 0) {
        md.push(`| \`${row.spec.path}\` | ${row.spec.lines} | — unpaired | |`);
      } else {
        const first = row.twins
          .map((twin) => `\`${twin.path}\``)
          .join('</br>');
        const second = row.twins.map((twin) => `${twin.lines}`).join('</br>');
        md.push(`| \`${row.spec.path}\` | ${row.spec.lines} | ${first} | ${second} |`);
      }
    }
    md.push('');
  }

  md.push('## Generated twins refused');
  md.push('');
  md.push(`Machine-written files that share a spec basename and were refused as twins (${generated.length}). They are the spec working as intended, not duplication:`);
  md.push('');
  if (generated.length > 0) {
    md.push('| file | refused because |');
    md.push('| --- | --- |');
    for (const entry of generated) {
      md.push(`| \`${entry.path}\` | ${entry.reason} |`);
    }
  } else {
    md.push('(none)');
  }
  md.push('');

  md.push('## Notes');
  md.push('');
  md.push(`- The naive count of ${allSpecPaths.length} includes ${worktreeCopyCount} worktree copies under \`.claude/worktrees/\` inside the \`trios-mesh\` tree — the same specs directory duplicated by an agent worktree. ${distinctSpecs.length} distinct specifications exist, not ${allSpecPaths.length}.`);
  md.push('- `queen_core.t27` (production) has no hand-written twin under the basename convention at census time. Its decisions do exist as hand-written Swift under other names (`QueenRetryPolicy`, `QueenReviewDecision`, `QueenMergeGate`, `QueenDelegationPolicy` in `agent-server/queen-core/`), but the convention this census checks is basename equality, and a judgement-based pairing would not be checkable.');
  md.push('- `a2a.t27` (production) pairs with `agent-server/apps/server/src/api/routes/a2a.ts`.');
  md.push('- `wire.t27` (mesh) pairs with the hand-written `src/wire.rs` in the same tree; the generated `gen/rust/wire.rs` is refused above.');
  md.push('');
  writeFileSync(OUT_PATH, md.join('\n') + '\n');
}

main();
